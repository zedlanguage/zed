//! `progress SPEC_DIR [current-step]` writes `SPEC_DIR/PROGRESS.md`: every step of DESIGN.md's
//! plan (sec:steps), grouped by layer, checked when this repository's STATUS.md Steps table
//! marks it done. CI does not run it, since CI never reads the spec.

use std::collections::HashSet;
use std::fmt::Write;

use crate::{Outcome, arg, impl_root, say};

/// The length of a step name at the start of `s`: `M0.n`, `Lk.n` or `S.n`, then an optional
/// lower-case letter.
fn step_name(s: &str) -> Option<usize> {
    let digits_from = |at: usize| {
        let rest = &s[at..];
        at + rest
            .find(|c: char| !c.is_ascii_digit())
            .unwrap_or(rest.len())
    };
    let after_layer = if s.starts_with("M0") {
        2
    } else if s.starts_with('S') {
        1
    } else if s.starts_with('L') {
        let end = digits_from(1);
        if end == 1 {
            return None;
        }
        end
    } else {
        return None;
    };
    let number = after_layer + 1;
    if !s[after_layer..].starts_with('.') {
        return None;
    }
    let end = digits_from(number);
    if end == number {
        return None;
    }
    let letter = s[end..]
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_lowercase());
    Some(end + usize::from(letter))
}

/// The step of a plan line: its name and the text after it.
fn step_line(line: &str) -> Option<(&str, &str)> {
    let s = line
        .strip_prefix("**")
        .or(line.strip_prefix('*'))
        .unwrap_or(line);
    let end = step_name(s)?;
    let rest = s[end..].strip_prefix('.')?;
    Some((&s[..end], rest.trim_start()))
}

/// The step a row of the Steps table marks done.
fn done_row(line: &str) -> Option<&str> {
    let s = line.strip_prefix('|')?.trim_start_matches(' ');
    let end = step_name(s)?;
    let rest = s[end..].trim_start_matches(' ').strip_prefix('|')?;
    rest.trim_start_matches(' ')
        .starts_with("done")
        .then_some(&s[..end])
}

/// A step's title: the text up to its first sentence's end or its ` — test` clause, in at most
/// 110 characters.
fn title_of(text: &str) -> String {
    let text = text.replace("**", "");
    let mut end = text.len();
    let mut previous = None;
    for (i, c) in text.char_indices() {
        if c.is_whitespace() {
            let after = text[i + c.len_utf8()..].strip_prefix('—');
            let test = after.is_some_and(|a| a.trim_start().starts_with("test"));
            if previous == Some('.') || test {
                end = i;
                break;
            }
        }
        previous = Some(c);
    }
    let title = text[..end].trim();
    if title.chars().count() <= 110 {
        return title.into();
    }
    let kept: String = title.chars().take(107).collect();
    format!("{}…", kept.trim_end())
}

/// The layers of the plan in `design`: each one's heading and steps.
type Layers<'a> = Vec<(&'a str, Vec<(&'a str, String)>)>;

fn plan(design: &str) -> Result<Layers<'_>, String> {
    let mut lines = design
        .lines()
        .skip_while(|l| *l != "## (sec:steps) The steps, layer by layer");
    if lines.next().is_none() {
        return Err("DESIGN.md has no section sec:steps".into());
    }
    let mut layers: Layers<'_> = Vec::new();
    for line in lines.take_while(|l| !l.starts_with("# ")) {
        if let Some(name) = line.strip_prefix("### ") {
            layers.push((name, Vec::new()));
        } else if let (Some((step, text)), Some(layer)) = (step_line(line), layers.last_mut()) {
            layer.1.push((step, title_of(text)));
        }
    }
    Ok(layers)
}

/// The text of PROGRESS.md, and how many steps are done of how many.
pub fn render(
    design: &str,
    status: &str,
    current: Option<&str>,
) -> Result<(String, usize, usize), String> {
    // M0.2 and M0.3 were written in the spec itself (STATUS.md, "M0.3 — desugaring rules").
    let done: HashSet<&str> = status
        .lines()
        .filter_map(done_row)
        .chain(["M0.2", "M0.3"])
        .collect();
    let layers = plan(design)?;
    let steps = || layers.iter().flat_map(|l| &l.1);
    let total = steps().count();
    let n_done = steps().filter(|s| done.contains(s.0)).count();
    let in_progress = current.map_or(String::new(), |c| format!(" In progress: **{c}**."));
    let mut out = format!(
        "# Implementation progress\n\nGenerated by the `progress` tool of `zed-impl` from \
         DESIGN.md's plan (sec:steps) and the\nSteps table of `zed-impl/STATUS.md`, after every \
         step.\n\n**{n_done} of {total} steps done.**{in_progress}\n\n"
    );
    for (name, steps) in &layers {
        let k = steps.iter().filter(|s| done.contains(s.0)).count();
        writeln!(out, "## {name} ({k}/{})\n", steps.len()).expect("writing to a String");
        for (s, title) in steps {
            let mark = if done.contains(s) { 'x' } else { ' ' };
            let tail = if Some(*s) == current {
                "  ← in progress"
            } else {
                ""
            };
            writeln!(out, "- [{mark}] **{s}** {title}{tail}").expect("writing to a String");
        }
        out.push('\n');
    }
    out.pop();
    Ok((out, n_done, total))
}

/// Runs the tool.
pub fn run(args: &[String], out: &mut String) -> Outcome {
    let root = arg(args, 0, "progress SPEC_DIR [current-step]")?;
    let read = |p: String| std::fs::read_to_string(&p).map_err(|e| format!("{p}: {e}"));
    let design = read(format!("{root}/DESIGN.md"))?;
    let status = read(format!("{}/STATUS.md", impl_root()))?;
    let current = args.get(1).map(String::as_str);
    let (text, n_done, total) = render(&design, &status, current)?;
    let path = format!("{root}/PROGRESS.md");
    std::fs::write(&path, text).map_err(|e| format!("{path}: {e}"))?;
    say!(out, "{n_done}/{total} done");
    Ok(true)
}
