#!/usr/bin/env python3
"""Writes ../zed/PROGRESS.md: every step of DESIGN.md's plan (sec:steps), grouped by layer,
checked when STATUS.md's Steps table marks it done. Not run by CI, which never reads the spec.

Usage: python3 -B tools/progress.py [current-step]
"""
import re, sys, pathlib

impl = pathlib.Path(__file__).resolve().parent.parent
spec = impl.parent / "zed"
design = (spec / "DESIGN.md").read_text().splitlines()
status = (impl / "STATUS.md").read_text()

done = set(re.findall(r"^\| *((?:M0|L\d+|S)\.\d+[a-z]?) *\| *done", status, re.M))
done |= {"M0.2", "M0.3"}  # written in the spec itself (STATUS.md, "M0.3 — desugaring rules")
current = sys.argv[1] if len(sys.argv) > 1 else None

start = design.index("## (sec:steps) The steps, layer by layer")
step = re.compile(r"^\*{0,2}((?:M0|L\d+|S)\.\d+[a-z]?)\.\s*(.*)")
layers, total = [], 0
for line in design[start + 1:]:
    if line.startswith("# "):
        break
    if line.startswith("### "):
        layers.append((line[4:], []))
        continue
    m = step.match(line)
    if m and layers:
        title = re.sub(r"\*\*", "", m.group(2))
        title = re.split(r"(?<=\.)\s|\s—\s*test", title)[0].strip()
        if len(title) > 110:
            title = title[:107].rstrip() + "…"
        layers[-1][1].append((m.group(1), title))
        total += 1

ndone = sum(1 for _, steps in layers for s, _ in steps if s in done)
out = ["# Implementation progress", "",
       "Generated by `zed-impl/tools/progress.py` from DESIGN.md's plan (sec:steps) and the",
       "Steps table of `zed-impl/STATUS.md`, after every step.", "",
       f"**{ndone} of {total} steps done.**" + (f" In progress: **{current}**." if current else ""), ""]
for name, steps in layers:
    k = sum(1 for s, _ in steps if s in done)
    out += [f"## {name} ({k}/{len(steps)})", ""]
    for s, title in steps:
        mark = "x" if s in done else " "
        tail = "  ← in progress" if s == current else ""
        out.append(f"- [{mark}] **{s}** {title}{tail}")
    out.append("")
(spec / "PROGRESS.md").write_text("\n".join(out))
print(f"{ndone}/{total} done")
