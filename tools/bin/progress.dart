/// Writes ../zed/PROGRESS.md: every step of DESIGN.md's plan (sec:steps), grouped by layer,
/// checked when STATUS.md's Steps table marks it done, and marked `[d]` once dart/PORTED lists
/// it as ported to Dart. Not run by CI, which never reads the spec.
///
/// Usage: dart tools/bin/progress.dart [current-step]
library;

import 'dart:io';

void main(List<String> args) {
  final impl = File.fromUri(Platform.script).parent.parent.parent;
  final spec = Directory('${impl.parent.path}/zed');
  final design = File('${spec.path}/DESIGN.md').readAsLinesSync();
  final status = File('${impl.path}/STATUS.md').readAsStringSync();

  final done = {
    for (final m in RegExp(
      r'^\| *((?:M0|L\d+|S)\.\d+[a-z]?) *\| *done',
      multiLine: true,
    ).allMatches(status))
      m[1]!,
    // Written in the spec itself (STATUS.md, "M0.3 — desugaring rules").
    'M0.2', 'M0.3',
  };
  final ported = {
    for (final l in File('${impl.path}/dart/PORTED').readAsLinesSync())
      if (l.trim().isNotEmpty && !l.startsWith('#')) l.trim(),
  };
  final current = args.firstOrNull;

  final start = design.indexOf('## (sec:steps) The steps, layer by layer');
  final step = RegExp(r'^\*{0,2}((?:M0|L\d+|S)\.\d+[a-z]?)\.\s*(.*)');
  final layers = <(String, List<(String, String)>)>[];
  var total = 0;
  for (final line in design.skip(start + 1)) {
    if (line.startsWith('# ')) break;
    if (line.startsWith('### ')) {
      layers.add((line.substring(4), []));
      continue;
    }
    final m = step.firstMatch(line);
    if (m != null && layers.isNotEmpty) {
      var title = m[2]!.replaceAll('**', '');
      title = title.split(RegExp(r'(?<=\.)\s|\s—\s*test'))[0].trim();
      final chars = title.runes.toList();
      if (chars.length > 110) {
        title = '${String.fromCharCodes(chars.take(107)).trimRight()}…';
      }
      layers.last.$2.add((m[1]!, title));
      total++;
    }
  }

  final all = [for (final (_, steps) in layers) ...steps.map((s) => s.$1)];
  final nDone = all.where(done.contains).length;
  final nPorted = all.where(ported.contains).length;
  final out = [
    '# Implementation progress',
    '',
    'Generated by `zed-impl/tools/bin/progress.dart` from DESIGN.md\'s plan (sec:steps) and the',
    'Steps table of `zed-impl/STATUS.md`, after every step. `[d]` marks a step ported from Rust',
    'to Dart (`zed-impl/dart/PORTED`).',
    '',
    '**$nDone of $total steps done, $nPorted ported to Dart.**'
        '${current != null ? ' In progress: **$current**.' : ''}',
    '',
  ];
  for (final (name, steps) in layers) {
    final k = steps.where((s) => done.contains(s.$1)).length;
    out.addAll(['## $name ($k/${steps.length})', '']);
    for (final (s, title) in steps) {
      final mark = ported.contains(s) ? 'd' : (done.contains(s) ? 'x' : ' ');
      final tail = s == current ? '  ← in progress' : '';
      out.add('- [$mark] **$s** $title$tail');
    }
    out.add('');
  }
  File('${spec.path}/PROGRESS.md').writeAsStringSync(out.join('\n'));
  print('$nDone/$total done');
}
